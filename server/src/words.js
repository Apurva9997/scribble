const SINGLE = WORDS.filter((word) => /^[a-z]+$/.test(word));
const UNIQUE = [...new Set(SINGLE)];

export const WORD_BANK = UNIQUE;

export function pickWords(count, exclude = []) {
  const banned = new Set(exclude.map((word) => word.toLowerCase()));
  const pool = WORD_BANK.filter((word) => !banned.has(word));
  const source = pool.length >= count ? pool : WORD_BANK;
  const copy = [...source];
  for (let i = copy.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [copy[i], copy[j]] = [copy[j], copy[i]];
  }
  return copy.slice(0, count);
}
